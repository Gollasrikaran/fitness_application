"""One-time generator: the FULL 171-pair x 12-activity condition-interaction
review matrix, for a single complete doctor sign-off pass (per user request:
review everything once, not in repeated small batches).

Writes data/condition_interactions_DRAFT_for_review.csv (overwrites any
earlier draft). NOT loaded by app.catalog.loader — this is a review artifact,
not production data. After the doctor reviews, copy only the rows they
actually APPROVE into the real data/condition_interactions.csv, then re-run
`python -m app.catalog.loader`.

IMPORTANT HONESTY NOTE (read before trusting this file for anything): this
was generated by an AI reasoning about anatomy/shared mechanism, NOT written
or reviewed by a licensed physician. It is offered at the same level of
authority as the existing data/safety_grid.csv, which is itself labeled
"product-team (not clinically reviewed)" throughout — i.e. a reasoned
starting draft, not a clinical determination. Every row's `note` states the
actual mechanism being claimed so a real reviewer can judge it on the merits.

Method: for every pair+activity cell, the default is simply the worse of the
two single-condition verdicts already in data/safety_grid.csv (no
escalation — "nothing beyond what each condition alone already says"). On
top of that default, a small number of CLUSTERS — groups of conditions that
plausibly compound through a shared, nameable anatomical/physiological
mechanism — escalate specific cells. Clusters are defined once below; the
pairwise combinatorics within each cluster are then generated mechanically,
not hand-typed, so the actual clinical judgment (which clusters are real,
and why) is auditable in one place instead of buried in 2,000 rows.
"""
import csv
import itertools
from pathlib import Path

DATA = Path(__file__).resolve().parents[2] / "data"
RANK = {"safe": 0, "modify": 1, "avoid": 2}


def load_grid():
    grid = {}
    with (DATA / "safety_grid.csv").open(encoding="utf-8") as f:
        for r in csv.DictReader(f):
            grid[(r["condition_code"], r["activity_type"])] = r["verdict"]
    return grid


def load_supported_conditions():
    out = []
    with (DATA / "conditions.csv").open(encoding="utf-8") as f:
        for r in csv.DictReader(f):
            if r["bucket"] == "supported" and r["condition_code"] != "none":
                out.append(r["condition_code"])
    return sorted(out)


def load_activities():
    with (DATA / "activity_taxonomy.csv").open(encoding="utf-8") as f:
        return [r["activity_type"] for r in csv.DictReader(f)]


GRID = load_grid()


def verdict_of(condition, activity):
    return GRID.get((condition, activity), "safe")


# ---------------------------------------------------------------------------
# CLUSTERS — the actual clinical judgment calls. Each is a group of
# conditions sharing a real mechanism, the activities that mechanism plays
# out through, the escalation rule, and a human-readable rationale template.
# The combinatorics (which pairs, which already-avoid cells to skip as
# redundant) are generated mechanically below, not by hand.
# ---------------------------------------------------------------------------

CLUSTERS = [
    {
        "name": "Spine-diagnosis stacking",
        "conditions": ["chronic_back_pain", "herniated_disk", "degenerative_disc",
                       "spinal_stenosis", "spondylosis"],
        "activities": {
            "running": "Repeated impact loading on the spine — two distinct spine "
                       "diagnoses together is a more complex, less stable picture "
                       "than either alone.",
            "dead_bug": "Requires a neutral spine held under load throughout — two "
                        "compounding spine diagnoses raises the risk of the lower "
                        "back lifting off the floor, the exact failure mode each "
                        "single-condition note already warns about.",
            "lower_back_side_stretch": "Direct lateral spine flexion — two spine "
                        "diagnoses together increases the chance of a symptom "
                        "change from the same motion.",
            "hamstring_stretch": "Seated/loaded-flexion hamstring stretch — two "
                        "spine diagnoses compounding the same flexed-spine concern.",
        },
        "min_rank": "modify",   # only escalate pairs where BOTH are already >= this
        "escalate_to": "avoid",
    },
    {
        "name": "Weight-bearing joint / inflammatory joint stacking",
        "conditions": ["arthritis_hip", "bursitis", "arthritis_knee", "gout", "obesity"],
        "activities": {
            "running": "Repeated impact loading stresses multiple joint/weight "
                       "factors at once — a materially different picture than any "
                       "one of them alone.",
            "quad_stretch": "Deep hip/knee flexion under stretch — two joint "
                       "conditions compounding the same loaded-flexion concern.",
            "glute_bridge": "Hip extension under load — two joint conditions "
                       "compounding the same hip-loading concern.",
        },
        "min_rank": "modify",
        "escalate_to": "avoid",
    },
    {
        "name": "Cardiometabolic risk-factor clustering (running only)",
        "conditions": ["obesity", "diabetes_controlled", "bp_controlled",
                       "prediabetes", "high_cholesterol", "pcos"],
        "activities": {
            "running": "Sustained vigorous exertion. Clinically recognized pattern: "
                       "concurrent cardiometabolic risk factors (central weight, "
                       "dysglycemia, hypertension, dyslipidemia, PCOS-linked "
                       "insulin resistance) carry materially higher combined risk "
                       "during unsupervised vigorous exertion than any one factor "
                       "alone — the same reasoning behind pre-exercise cardiac risk "
                       "stratification checklists.",
        },
        "min_rank": "safe",  # prediabetes/high_cholesterol/pcos carry NO individual
        # restriction at all — the whole point of this cluster is that the
        # CONJUNCTION of risk factors matters even when no single one does.
        "escalate_to": "avoid",
        # Two "safe"-individually risk factors together (e.g. prediabetes +
        # high_cholesterol, neither restricted alone) land at a lesser
        # escalation than a pair involving an already-"modify" member.
        "escalate_to_if_both_only_safe": "modify",
    },
]

# Lower-confidence, hand-picked additions — included separately because they
# don't fit a clean cluster rule, and flagged explicitly as weaker so the
# reviewer can triage them differently from the cluster-generated rows above.
LOWER_CONFIDENCE = {
    ("bursitis", "carpal_tunnel", "wrist_circles"): ("modify",
        "carpal_tunnel alone is already modify for wrist_circles; bursitis alone is "
        "safe for wrist_circles but modify for shoulder_circles (overlapping "
        "joint-inflammation concern) — escalating wrist_circles to a firmer modify "
        "reflects the combined wrist/shoulder inflammation picture, but the basis "
        "is weaker than the cluster rows above."),
}
# sprain_strain is deliberately EXCLUDED from cluster generation: the
# condition is site-nonspecific ("sprain / pulled muscle" could be anywhere),
# so pairing it with a site-specific condition (e.g. a spine diagnosis) can't
# be asserted to share an anatomical site with any confidence — a real
# reviewer would need to know WHERE the sprain actually is, which this app's
# condition list doesn't capture. Left as a known limitation rather than
# guessed at.
#
# depression and anxiety are deliberately EXCLUDED: both are individually
# "no physical exercise restriction identified" (data/conditions.csv), and
# there is no physical/anatomical mechanism by which a mental-health
# condition would compound a PHYSICAL activity-safety risk. Inventing one
# would be clinically inappropriate — conflating mental health with physical
# exercise restriction with no actual mechanism behind it.
EXCLUDED_CONDITIONS_NOTE = (
    "sprain_strain excluded from cluster generation (site-nonspecific — cannot "
    "confirm anatomical overlap with another condition); depression and anxiety "
    "excluded (no physical mechanism for a physical-activity interaction)."
)


def build_flagged():
    flagged = {}  # (a, b, activity) sorted -> (verdict, note, cluster_name)
    for cluster in CLUSTERS:
        conds = cluster["conditions"]
        for a, b in itertools.combinations(sorted(conds), 2):
            for activity, mechanism in cluster["activities"].items():
                va, vb = verdict_of(a, activity), verdict_of(b, activity)
                min_rank = RANK[cluster["min_rank"]]
                if RANK[va] < min_rank or RANK[vb] < min_rank:
                    continue  # one of the pair doesn't actually touch this activity
                if va == "avoid" or vb == "avoid":
                    continue  # already blocked by the single-condition grid alone — redundant
                verdict = cluster["escalate_to"]
                if (cluster.get("escalate_to_if_both_only_safe")
                        and va == "safe" and vb == "safe"):
                    verdict = cluster["escalate_to_if_both_only_safe"]
                note = (f"[{cluster['name']}] {mechanism} "
                        f"(single verdicts: {a}={va}, {b}={vb}).")
                flagged[(a, b, activity)] = (verdict, note)
    flagged.update(LOWER_CONFIDENCE)
    return flagged


ALREADY_LIVE = {
    ("arthritis_knee", "obesity", "running"): ("avoid",
        "[Weight-bearing joint / inflammatory joint stacking] Extra body weight "
        "multiplies repeated impact loading on an already-damaged knee joint. "
        "(Already live in data/condition_interactions.csv.)"),
}


def main():
    flagged = build_flagged()
    conditions = load_supported_conditions()
    activities = load_activities()
    pairs = list(itertools.combinations(conditions, 2))

    out_path = DATA / "condition_interactions_DRAFT_for_review.csv"
    n_default = n_flagged = n_live = 0
    with out_path.open("w", encoding="utf-8", newline="") as f:
        w = csv.writer(f)
        w.writerow(["condition_a", "condition_b", "activity_type", "verdict",
                    "status", "note", "single_a_verdict", "single_b_verdict"])
        for a, b in pairs:
            for activity in activities:
                va, vb = verdict_of(a, activity), verdict_of(b, activity)
                key = (a, b, activity)
                if key in ALREADY_LIVE:
                    verdict, note = ALREADY_LIVE[key]
                    status = "APPROVED (already live)"
                    n_live += 1
                elif key in flagged:
                    verdict, note = flagged[key]
                    status = "FLAGGED - review this escalation"
                    n_flagged += 1
                else:
                    verdict = max(va, vb, key=lambda v: RANK[v])
                    note = ("No combined-risk mechanism identified — matches the "
                            "worse of the two single-condition verdicts, no "
                            "escalation proposed.")
                    status = "default (no escalation proposed)"
                    n_default += 1
                w.writerow([a, b, activity, verdict, status, note, va, vb])

    total = n_default + n_flagged + n_live
    print(f"wrote {total} rows to {out_path}")
    print(f"  default (no escalation): {n_default}")
    print(f"  FLAGGED for review:      {n_flagged}")
    print(f"  already live:            {n_live}")
    print(f"\n{EXCLUDED_CONDITIONS_NOTE}")


if __name__ == "__main__":
    main()
